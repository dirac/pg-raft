#!/bin/bash
# Generate the multi-machine configs into multi/gen/ from the single-machine ones:
#   raft-3.toml, raft-5.toml   raft/config.toml with the node machines, dir, backup_store, pg_hba
#   std-3.sh, std-5.sh         HOSTS / PORTS / PG_HBA for std/ (STD_CLUSTER)
#   solo.sh                    solo/ on node 0's machine (SOLO_CLUSTER)
# RAFT_SYNC=1: leader_sync and follower_sync true in the raft configs (the ledger synced on the
# commit path, like std's and solo's fsync = on). PG_FSYNC=off: fsync = off for std and solo
# (PG_CONF in their cluster files), like pg-raft's syncs off. COMMIT_WAIT=sync_rep: commit_wait in
# the raft configs (the commit waits in PostgreSQL's synchronous replication). WAL_CAPTURE=hook:
# wal_capture = "hook" and install_dir = HOOK_INSTALL_DIR (pg-raft's PostgreSQL with the
# pg_raft_wal extension) in the raft configs. MAX_CONNECTIONS=N: max_connections for all three.
# WAL_COMPRESSION=off|pglz|lz4|zstd: wal_compression for all three (lz4 by default, in the configs).
set -euo pipefail
source "$(dirname "$0")/lib.sh"

mkdir -p "$GEN_DIR"
pg_lines=()
[[ "${PG_FSYNC:-on}" == off ]] && pg_lines+=('"fsync = off"')
[[ -n "${MAX_CONNECTIONS:-}" ]] && pg_lines+=("\"max_connections = $MAX_CONNECTIONS\"")
[[ -n "${WAL_COMPRESSION:-}" ]] && pg_lines+=("\"wal_compression = $WAL_COMPRESSION\"")
pg_conf=""
(( ${#pg_lines[@]} )) && pg_conf="PG_CONF=(${pg_lines[*]})"
capture="${WAL_CAPTURE:-fuse}"
[[ "$capture" == fuse || "$capture" == hook ]] || die "WAL_CAPTURE=$capture: fuse or hook"
hook_install="${HOOK_INSTALL_DIR:-/opt/pg_raft/build/postgresql}"
src="$MULTI_DIR/../raft/config.toml"

for n in "${NODE_SIZES[@]}"; do
  {
    echo "# Generated by multi/gen.sh from raft/config.toml: $n nodes on separate machines."
    # Everything before the first [[server]], with dir, backup_store and pg_hba replaced.
    awk -v dir="$REMOTE_DIR/raft/data" -v store="$SHARED/backups" -v net="$NETWORK" \
        -v sync="${RAFT_SYNC:-0}" -v wait="${COMMIT_WAIT:-fsync}" \
        -v capture="$capture" -v install="$hook_install" '
      /^\[\[server\]\]/            { exit }
      sync == 1 && /^(leader|follower)_sync[[:space:]]*=/ { sub(/false/, "true") }
      /^commit_wait[[:space:]]*=/  { print "commit_wait = \"" wait "\""; next }
      /^dir[[:space:]]*=/          { print "dir          = \"" dir "\""; next }
      /^backup_store[[:space:]]*=/ { print "backup_store = \"" store "\""; next }
      /^pg_hba[[:space:]]*=/       { print "pg_hba = [\"host all all " net " trust\"]"; skip = 1; next }
      skip && /^\]/                { skip = 0; next }
      skip                         { next }
      { print }
      END {
        if (capture == "hook")
          printf "wal_capture = \"hook\"\ninstall_dir = \"%s\"\n\n", install
      }' "$src"
    for ((i = 0; i < n; i++)); do
      printf '[[server]]\nhostname = "%s"\npg_port  = %d\nha_port  = %d\n\n' \
        "${NODE_HOSTS[$i]}" $((5441 + i)) $((7001 + i))
    done
    sed -n '/^\[pg_config\]/,$p' "$src" |
      if [[ -n "${MAX_CONNECTIONS:-}" ]]; then
        sed -E "s/^max_connections[[:space:]]*=.*/max_connections    = $MAX_CONNECTIONS/"
      else cat; fi |
      if [[ -n "${WAL_COMPRESSION:-}" ]]; then
        sed -E "s/^wal_compression[[:space:]]*=.*/wal_compression    = \"$WAL_COMPRESSION\"/"
      else cat; fi
  } > "$GEN_DIR/raft-$n.toml"

  hosts="" ports=""
  for ((i = 0; i < n; i++)); do hosts+=" ${NODE_HOSTS[$i]}"; ports+=" $((5532 + i))"; done
  cat > "$GEN_DIR/std-$n.sh" <<EOF
# Generated by multi/gen.sh: $n nodes on separate machines (node 0 is the primary).
HOSTS=(${hosts# })
PORTS=(${ports# })
DATA_ROOT="\${DATA_ROOT:-\$STD_DIR/data}"
PG_HBA=(
  "host replication all $NETWORK trust"
  "host all         all $NETWORK trust"
)
$pg_conf
EOF
done

cat > "$GEN_DIR/solo.sh" <<EOF
# Generated by multi/gen.sh: the single PostgreSQL on node 0's machine.
HOST=${NODE_HOSTS[0]}
PORT=5632
DATA_ROOT="\${DATA_ROOT:-\$SOLO_DIR/data}"
PG_HBA=(
  "host all all $NETWORK trust"
)
$pg_conf
EOF
log "configs in $GEN_DIR: $(cd "$GEN_DIR" && echo *)"
