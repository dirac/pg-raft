#!/bin/bash
# Generate the multi-machine configs into multi/gen/ from the single-machine ones:
#   raft-3.toml, raft-5.toml   raft/config.toml with the node machines, dir, backup_store, pg_hba
#   std-3.sh, std-5.sh         HOSTS / PORTS / PG_HBA for std/ (STD_CLUSTER)
#   solo.sh                    solo/ on node 0's machine (SOLO_CLUSTER)
# RAFT_SYNC=1: leader_sync, follower_sync and log_sync all true in the raft configs (disk syncs on
# the commit path, like std's and solo's fsync = on).
set -euo pipefail
source "$(dirname "$0")/lib.sh"

mkdir -p "$GEN_DIR"
src="$MULTI_DIR/../raft/config.toml"

for n in 3 5; do
  {
    echo "# Generated by multi/gen.sh from raft/config.toml: $n nodes on separate machines."
    # Everything before the first [[server]], with dir, backup_store and pg_hba replaced.
    awk -v dir="$REMOTE_DIR/raft/data" -v store="$SHARED/backups" -v net="$NETWORK" \
        -v sync="${RAFT_SYNC:-0}" '
      /^\[\[server\]\]/            { exit }
      sync == 1 && /^(leader|follower|log)_sync[[:space:]]*=/ { sub(/false/, "true") }
      /^dir[[:space:]]*=/          { print "dir          = \"" dir "\""; next }
      /^backup_store[[:space:]]*=/ { print "backup_store = \"" store "\""; next }
      /^pg_hba[[:space:]]*=/       { print "pg_hba = [\"host all all " net " trust\"]"; skip = 1; next }
      skip && /^\]/                { skip = 0; next }
      skip                         { next }
      { print }' "$src"
    for ((i = 0; i < n; i++)); do
      printf '[[server]]\nhostname = "%s"\npg_port  = %d\nha_port  = %d\n\n' \
        "${NODE_HOSTS[$i]}" $((5441 + i)) $((7001 + i))
    done
    sed -n '/^\[pg_config\]/,$p' "$src"
  } > "$GEN_DIR/raft-$n.toml"

  hosts="" ports=""
  for ((i = 0; i < n; i++)); do hosts+=" ${NODE_HOSTS[$i]}"; ports+=" $((5532 + i))"; done
  cat > "$GEN_DIR/std-$n.sh" <<EOF
# Generated by multi/gen.sh: $n nodes on separate machines (node 0 is the primary).
HOSTS=(${hosts# })
PORTS=(${ports# })
DATA_ROOT="\${DATA_ROOT:-\$STD_DIR/data}"
PG_HBA=(
  "host replication all $NETWORK trust"
  "host all         all $NETWORK trust"
)
EOF
done

cat > "$GEN_DIR/solo.sh" <<EOF
# Generated by multi/gen.sh: the single PostgreSQL on node 0's machine.
HOST=${NODE_HOSTS[0]}
PORT=5632
DATA_ROOT="\${DATA_ROOT:-\$SOLO_DIR/data}"
PG_HBA=(
  "host all all $NETWORK trust"
)
EOF
log "configs in $GEN_DIR: $(cd "$GEN_DIR" && echo *)"
